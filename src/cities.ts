export const DEFAULT_CITY = "北京|101010100";

export function cityLabel(city: City): string {
  return city.name === city.province ? city.name : `${city.name} · ${city.province}`;
}

export function cityValue(city: City): string {
  return `${city.name}|${city.id}`;
}

export function cityFromValue(value: string | null): City {
  const id = value?.split("|")[1];
  return CITIES.find((city) => city.id === id) ?? CITIES[0];
}

export function findCity(query: string): City | null {
  const text = query.trim();
  const labeled = CITIES.find((city) => cityLabel(city) === text);
  if (labeled) return labeled;
  const named = CITIES.filter((city) => city.name === text || `${city.name}市` === text);
  return named.length === 1 ? named[0] : null;
}
